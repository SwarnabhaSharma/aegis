def generate_synthetic_alerts(es: Elasticsearch, index: str, count: int = 5) -> int:
    """Write synthetic alerts to the alert index for demo. Returns count written."""
    if not es.indices.exists(index=index):
        from aegis.incidents.es_store import _ALERT_MAPPINGS
        es.indices.create(index=index, mappings=_ALERT_MAPPINGS)

    written = 0
    for alert in SYNTHETIC_ALERTS[:count]:
        doc = {**alert, "@timestamp": datetime.now(UTC).isoformat()}
        es.index(index=index, document=doc, refresh=True)
        written += 1
    return written
