"""Elastic Security alert adapter — polls ES alert indices, normalizes to Aegis.

Supports two modes (configurable via es_alert_index):
  - Real Elastic Security: ".siem-signals-*" (reads actual detection alerts)
  - Synthetic/demo: "aegis-dev-alerts" (generated by generate_synthetic_alerts)

Architecture decision: Option 1+4 hybrid (Stage B, ADR-018).
"""

from datetime import UTC, datetime

from elasticsearch import Elasticsearch

from aegis.incidents.ingestion import ingest_alert
from aegis.incidents.schema import Incident


def normalize_elastic_alert(doc: dict) -> dict:
    """Translate ECS fields → Aegis fields dict."""
    rule = doc.get("rule", {})
    host = doc.get("host", {})
    user = doc.get("user", {})
    process = doc.get("process", {})
    source = doc.get("source", {})
    destination = doc.get("destination", {})
    file_ = doc.get("file", {})
    kibana = doc.get("kibana", {})

    alert_severity = rule.get("severity", kibana.get("alert", {}).get("severity"))

    return {
        "host": host.get("name", "unknown"),
        "user": user.get("name", "unknown"),
        "process": process.get("name", "unknown"),
        "pid": process.get("pid"),
        "parent_process": process.get("parent", {}).get("name"),
        "command_line": process.get("command_line"),
        "source_ip": source.get("ip"),
        "destination_ip": destination.get("ip"),
        "file_path": file_.get("path"),
        "source": "sysmon",
        "severity": _map_severity(alert_severity),
        "type": rule.get("name", "elastic-alert"),
        "elastic_alert_id": doc.get("_elastic_id"),
        "elastic_rule_id": rule.get("id"),
        "elastic_rule_name": rule.get("name"),
        "timestamp": doc.get("@timestamp"),
    }


def _map_severity(es_severity) -> str:
    """Map Elastic severity (0-100 or keyword) → Aegis (high/medium/low)."""
    if isinstance(es_severity, (int, float)):
        if es_severity >= 70:
            return "high"
        if es_severity >= 40:
            return "medium"
        return "low"
    mapping = {"critical": "high", "high": "high", "medium": "medium", "low": "low"}
    return mapping.get(str(es_severity).lower(), "medium")


class ElasticAlertPoller:
    """Polls ES security alert indices, normalizes to Aegis Alert model."""

    def __init__(self, es: Elasticsearch, alert_index: str, store, poll_interval: int = 30):
        self._es = es
        self._alert_index = alert_index
        self._store = store
        self._poll_interval = poll_interval

    def poll_once(self) -> list[Incident]:
        """One poll cycle: fetch uningested alerts → normalize → ingest."""
        body = {
            "query": {
                "bool": {
                    "must_not": {"term": {"aegis_ingested": True}},
                    "filter": {"range": {"@timestamp": {"gte": "now-1h"}}},
                }
            },
            "sort": [{"@timestamp": {"order": "asc"}}],
            "size": 10,
        }
        try:
            resp = self._es.search(index=self._alert_index, body=body)
        except Exception:
            return []

        incidents = []
        for hit in resp["hits"]["hits"]:
            alert_doc = hit["_source"]
            alert_doc["_elastic_id"] = hit["_id"]

            normalized = normalize_elastic_alert(alert_doc)
            incident = ingest_alert(
                store=self._store,
                source="elastic-security",
                fields=normalized,
                incident_type=normalized.get("type", "unknown"),
            )
            incidents.append(incident)

            # Mark as ingested for dedup
            try:
                self._es.update(
                    index=self._alert_index,
                    id=hit["_id"],
                    body={"doc": {"aegis_ingested": True, "aegis_incident_id": incident.id}},
                )
            except Exception:
                pass  # non-critical: worst case we re-ingest on next poll

        return incidents


